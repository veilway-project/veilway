import {parseHex, toHex} from "./color.ts";
import {BLUR_MAX, BUILTIN, COLOR_KEYS, MATERIAL, SHADOW_INK, WASH_STRENGTH, glassTints, palette, type Theme} from "./tokens.ts";

// The CSS variables of a theme. Colours are parsed and written out again from numbers, so no string from a theme file reaches a stylesheet. The tints of the floating and thick panes are worked out here from the palette, the tint and the blur; a theme file cannot set them.
export function themeVars(theme: Theme): Record<string, string> {
	const vars: Record<string, string> = {};
	for (const key of COLOR_KEYS) {
		const parsed = parseHex(theme.colors[key]);
		if (!parsed) throw new Error("theme colour is not #RRGGBB: " + key);
		vars["--c-" + key.replace(/[A-Z0-9]/g, m => "-" + m.toLowerCase())] = toHex(parsed);
	}
	const tint = Math.min(1, Math.max(0, Number(theme.glass.tint) || 0)), blur = Math.min(BLUR_MAX, Math.max(0, Math.round(Number(theme.glass.blur) || 0))), tints = glassTints(palette(theme), tint, blur);
	vars["--glass-tint"] = String(tint);
	vars["--glass-tint-float"] = String(tints.float);
	vars["--glass-tint-thick"] = String(tints.thick);
	vars["--glass-blur"] = blur + "px";
	return vars;
}

// Puts a validated theme on an element, or with null hands the element back to the built-in stylesheet.
export function applyTheme(el: HTMLElement, theme: Theme | null): void {
	for (const name of Object.keys(themeVars(BUILTIN.dark))) el.style.removeProperty(name);
	if (theme) for (const [name, value] of Object.entries(themeVars(theme))) el.style.setProperty(name, value);
	if (theme) el.dataset.scheme = theme.scheme;
}

// The text of src/styles/colors.css. scripts/tokens.ts writes it and a test fails when the file on disk differs.
export function builtinCss(): string {
	const block = (scheme: "dark" | "light", indent: string) => ["color-scheme: " + scheme, ...Object.entries(themeVars(BUILTIN[scheme])).map(([k, v]) => k + ": " + v)].map(line => indent + line + ";\n").join("");
	const material = {"wash-strength": WASH_STRENGTH, "glow-1": MATERIAL.glow1, "glow-2": MATERIAL.glow2, "shaft": MATERIAL.shaft, "shaft-white": MATERIAL.shaftWhite, "sheen": MATERIAL.sheen, "shade": MATERIAL.shade, "well": MATERIAL.well, "scrim": MATERIAL.scrim, "shadow-ink-bg": SHADOW_INK};
	return "/* Generated by scripts/tokens.ts from src/theme/tokens.ts. Do not edit by hand. */\n"
		+ ":root {\n" + Object.entries(material).map(([k, v]) => "\t--" + k + ": " + Math.round(v * 100) + "%;\n").join("") + "\t--glass-saturate: " + MATERIAL.saturate + ";\n}\n"
		+ ":root, [data-scheme=\"dark\"] {\n" + block("dark", "\t") + "}\n"
		+ "@media (prefers-color-scheme: light) {\n\t:root:not([data-scheme]) {\n" + block("light", "\t\t") + "\t}\n}\n"
		+ "[data-scheme=\"light\"] {\n" + block("light", "\t") + "}\n";
}
